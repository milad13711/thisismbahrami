#!/usr/bin/env python3
"""Post-crawl build step: sitemaps, robots.txt, .htaccess (redirects + security), current site.js.

Run after tools/crawl.py:  python3 tools/finalize.py
"""
import json, os, re, shutil, ssl, sys, urllib.parse, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
DIST = sys.argv[1] if len(sys.argv) > 1 else 'site'
BASE = 'https://thisismbahrami.ir'
CTX = ssl.create_default_context(cafile='/etc/ssl/cert.pem')
EXCL = [l.strip() for l in open('tools/exclude.txt', encoding='utf-8') if l.strip() and not l.startswith('#')]
man = json.load(open('tools/crawl-manifest.json', encoding='utf-8'))
pages = set(man['pages'])

def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': 'static-export'}), timeout=60, context=CTX) as r:
        return r.read().decode('utf-8')

# 1. current front-end script (supports the ERP form) and the theme CSS from the repo
shutil.copy('../theme/milad-bahrami/assets/js/site.js', DIST + '/wp-content/themes/milad-bahrami/assets/js/site.js')
shutil.copy('../theme/milad-bahrami/assets/css/site.css', DIST + '/wp-content/themes/milad-bahrami/assets/css/site.css')

# 2. sitemaps: same file names Google already knows, only URLs that exist in this build
names = ['post-sitemap.xml', 'page-sitemap.xml', 'portfolio-sitemap.xml', 'faq-sitemap.xml', 'category-sitemap.xml', 'tests-urls.xml']
index_items = []
total = 0
for n in names:
    try:
        xml = get(BASE + '/' + n)
    except Exception as e:
        print('skip sitemap', n, e)
        continue
    xml = re.sub(r'<\?xml-stylesheet[^>]*\?>\s*', '', xml)
    def keep(m):
        loc = re.sub(r'^/\d{4}/\d{2}/\d{2}/', '/', urllib.parse.unquote(urllib.parse.urlparse(m.group(1)).path))
        if any(e in loc for e in EXCL): return ''
        if not (loc in pages or loc.rstrip('/') + '/' in pages): return ''
        # always publish the canonical (non-dated) URL
        return re.sub(r'<loc>[^<]+</loc>', '<loc>' + BASE + urllib.parse.quote(loc, safe='/') + '</loc>', m.group(0))
    xml = re.sub(r'<url>.*?<loc>([^<]+)</loc>.*?</url>\s*', keep, xml, flags=re.S)
    cnt = xml.count('<loc>')
    if cnt:
        open(os.path.join(DIST, n), 'w', encoding='utf-8').write(xml)
        index_items.append(n)
        total += cnt
        print(n, cnt)
idx = '<?xml version="1.0" encoding="UTF-8"?>\n<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + ''.join(
    '<sitemap><loc>%s/%s</loc></sitemap>\n' % (BASE, n) for n in index_items) + '</sitemapindex>\n'
open(DIST + '/sitemap_index.xml', 'w', encoding='utf-8').write(idx)
print('sitemap urls', total)

# 3. robots.txt
open(DIST + '/robots.txt', 'w', encoding='utf-8').write(
    'User-agent: *\nAllow: /\n\nSitemap: %s/sitemap_index.xml\n' % BASE)

# 4. .htaccess: redirects recorded from WordPress + hardening
red = []
for src, (code, dst) in sorted(man['redirects'].items()):
    if not dst or src == dst or src in pages: continue
    if any(e in src for e in EXCL): continue
    s = urllib.parse.quote(src.rstrip('/'), safe='/')
    d = urllib.parse.quote(dst, safe='/')
    if s in ('', '/'): continue
    red.append('RedirectMatch 301 ^%s/?$ %s%s' % (re.escape(urllib.parse.unquote(s)).replace('\\/', '/').replace('%', '%'), BASE, d))
extra = []
for line in open('tools/redirects.txt', encoding='utf-8'):
    line = line.strip()
    if not line or line.startswith('#'): continue
    a, b = line.split()
    extra.append('RedirectMatch 301 ^%s/?$ %s' % (re.escape(a.rstrip('/')).replace('\\/', '/'), BASE + urllib.parse.quote(b, safe='/')))
gone = [l.strip() for l in open('tools/gone.txt', encoding='utf-8') if l.strip() and not l.startswith('#')]
extra.append('RedirectMatch 410 ^/(%s)/?$' % '|'.join(re.escape(g) for g in gone))
extra.append('RedirectMatch 410 ^/(tag|author|feed|comments)(/.*)?$')
red = extra + red
ht = '''# Static site (no PHP). Generated by tools/finalize.py
Options -Indexes -MultiViews
DirectoryIndex index.html
ErrorDocument 404 /404.html
AddDefaultCharset UTF-8

# Nothing server-side runs here
<FilesMatch "\\.(php|phtml|phar|php[0-9]|inc|cgi|pl)$">
  Require all denied
</FilesMatch>
<FilesMatch "^\\.">
  Require all denied
</FilesMatch>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  Header always set X-Frame-Options "SAMEORIGIN"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=()"
</IfModule>

<IfModule mod_expires.c>
  ExpiresActive On
  ExpiresByType image/webp "access plus 1 year"
  ExpiresByType image/jpeg "access plus 1 year"
  ExpiresByType image/png "access plus 1 year"
  ExpiresByType image/svg+xml "access plus 1 year"
  ExpiresByType font/woff2 "access plus 1 year"
  ExpiresByType text/css "access plus 1 week"
  ExpiresByType application/javascript "access plus 1 week"
  ExpiresByType text/html "access plus 10 minutes"
</IfModule>

# Old WordPress URLs -> current ones
''' + '\n'.join(red) + '\n'
open(DIST + '/.htaccess', 'w', encoding='utf-8').write(ht)
print('redirect rules', len(red))
